"""Generate docs/data_model.md from the live warehouse schema.

Column names and types come from DuckDB itself, so the doc cannot drift from
the tables; descriptions are curated below and a test fails when a column has
none. Run `python scripts/describe_schema.py` after changing a table."""
from __future__ import annotations

TABLES = {
    "raw_weather_hourly": "Append-only city/hour records from Open-Meteo. Hours already loaded are refreshed in place when the model revises them. Hours are city-local.",
    "stg_hourly": "View over raw: typed, deduplicated, with unit-suffixed column names.",
    "mart_daily_city": "One row per city and city-local day. The current day includes forecast hours.",
    "mart_exposure_city": "Heat/cold hours and degree-hours per city-day (illustrative thresholds, not clinical guidance).",
    "fetch_log": "One row per city per fetch: when, how many hours returned, latest hour returned. Drives the source-fetch freshness gate.",
}

COLUMNS = {
    "city": "City name from config.CITIES.",
    "hour": "City-local hour (no timezone offset stored).",
    "day": "City-local calendar date.",
    "ingested_at": "When the row was last written or refreshed.",
    "temperature_2m": "Air temperature at 2 m, degrees C (raw).",
    "precipitation": "Precipitation, mm (raw, model output).",
    "wind_speed_10m": "Wind speed at 10 m, km/h (raw).",
    "temperature_c": "Air temperature, degrees C.",
    "precipitation_mm": "Precipitation, mm.",
    "wind_kmh": "Wind speed, km/h.",
    "avg_temp_c": "Mean of hourly temperature for the day, degrees C.",
    "min_temp_c": "Lowest hourly temperature, degrees C.",
    "max_temp_c": "Highest hourly temperature, degrees C.",
    "total_precip_mm": "Sum of hourly precipitation, mm.",
    "max_wind_kmh": "Highest hourly wind speed, km/h.",
    "hours_observed": "Hourly records in the day (24 when complete; model output, not station observations).",
    "heat_hours": "Hours at or above the heat threshold.",
    "cold_hours": "Hours at or below the cold threshold.",
    "heat_degree_hours": "Sum of degrees above the heat threshold across hours.",
    "cold_degree_hours": "Sum of degrees below the cold threshold across hours.",
    "fetched_at": "When the fetch ran.",
    "rows_returned": "Hourly rows returned by that fetch (0 means an empty fetch).",
    "latest_hour_returned": "Latest weather hour in that fetch (usually later than now: forecast horizon).",
}


def describe(con) -> list[tuple[str, list[tuple[str, str]]]]:
    """[(table, [(column, type)])] for the documented tables that exist."""
    out = []
    for name in TABLES:
        cols = con.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_name = ? ORDER BY ordinal_position", [name]).fetchall()
        if cols:
            out.append((name, cols))
    return out


def render(con) -> str:
    lines = ["# Data model", "",
             "Generated by `scripts/describe_schema.py` from the live DuckDB schema. All values are "
             "Open-Meteo model output (past days are model output too), not station observations.", ""]
    for table, cols in describe(con):
        lines += [f"## {table}", "", TABLES[table], "", "| Column | Type | Description |", "| --- | --- | --- |"]
        for col, typ in cols:
            lines.append(f"| {col} | {typ} | {COLUMNS.get(col, 'UNDOCUMENTED')} |")
        lines.append("")
    return "\n".join(lines)
